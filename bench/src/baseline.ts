/**
 * The committed baseline (`bench/baseline.json`) and the ratchet that guards it.
 *
 * The baseline records the outcome of every case, plus the per-rule and
 * per-category scores derived from them (the docs site renders those). The
 * ratchet compares case by case rather than rate by rate, so adding a case a
 * rule misses lowers no one's guard: it is a new known gap, recorded by
 * `bun run bench --update`. What fails is a case that got worse:
 *
 *   TP -> FN   the rule stopped catching something it caught (detection drops)
 *   TN -> FP   the rule started firing on a safe twin (false alarms rise)
 *
 * `--check` also fails when the baseline is merely out of date (an improvement,
 * a new or removed case, a changed title), so the numbers on the site are
 * always the numbers of the tree. `--update` refuses to record a regression
 * unless `--allow-regressions` is passed, so accepting one is a visible choice
 * in the diff of baseline.json, never a side effect.
 */
import type { Category } from './corpus';
import { scoreBy, scoreOf, type Score } from './metrics';
import type { CaseResult, LoadedPlugin, Outcome } from './score';

export interface BaselineCase {
  readonly outcome: Outcome;
  readonly category: string;
  readonly rule: string;
  readonly file: string;
  readonly line: number | null;
  readonly pair: string;
  readonly framework: string;
  readonly cwe: string | null;
  readonly title: string;
}

export interface BaselineRule extends Score {
  /** `recommended` when the preset turns it on, `override` when a category enables it. */
  readonly enabledBy: 'recommended' | 'override';
  readonly categories: readonly string[];
  readonly description: string;
  readonly url: string | null;
}

export interface BaselineCategory extends Score {
  readonly title: string;
  readonly cwe: string | null;
  readonly rules: readonly string[];
  readonly pairs: number;
  /** The rule entries layered over `recommended` for this category, as written in category.json. */
  readonly overrides: Readonly<Record<string, unknown>>;
}

export interface BaselinePlugin {
  readonly package: string;
  /** Every rule the plugin exports, measured or not, so the site can say which have no cases yet. */
  readonly rules: readonly string[];
}

export interface Baseline {
  readonly $comment: string;
  readonly schema: 1;
  readonly plugins: Readonly<Record<string, BaselinePlugin>>;
  readonly rules: Readonly<Record<string, BaselineRule>>;
  readonly categories: Readonly<Record<string, BaselineCategory>>;
  readonly cases: Readonly<Record<string, BaselineCase>>;
}

const COMMENT =
  'Generated by `bun run bench --update` from bench/corpus. Do not edit by hand: CI fails when this file and the tree disagree.';

function sortedRecord<T>(entries: Iterable<readonly [string, T]>): Record<string, T> {
  return Object.fromEntries([...entries].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

export function buildBaseline(
  results: readonly CaseResult[],
  categories: readonly Category[],
  plugins: ReadonlyMap<string, LoadedPlugin>,
): Baseline {
  const ruleScores = scoreBy(results, (r) => r.rule);
  const categoryScores = scoreBy(results, (r) => r.category);

  const rules = sortedRecord(
    [...ruleScores].map(([rule, score]) => {
      const [short = '', name = ''] = rule.split('/');
      const plugin = plugins.get(short);
      const meta = plugin?.plugin.rules[name]?.meta?.docs;
      const owning = categories.filter((c) => c.config.rules.includes(rule)).map((c) => c.id);
      const entry: BaselineRule = {
        ...score,
        enabledBy: plugin?.recommended.has(name) === true ? 'recommended' : 'override',
        categories: owning,
        description: meta?.description ?? '',
        url: meta?.url ?? null,
      };
      return [rule, entry] as const;
    }),
  );

  const categoryRecord = sortedRecord(
    categories.map((category) => {
      const entry: BaselineCategory = {
        ...(categoryScores.get(category.id) ?? scoreOf([])),
        title: category.config.title,
        cwe: category.config.cwe,
        rules: category.config.rules,
        pairs: new Set(category.cases.map((c) => c.meta.pair)).size,
        overrides: category.config.overrides,
      };
      return [category.id, entry] as const;
    }),
  );

  const cases = sortedRecord(
    results.map((r) => {
      const entry: BaselineCase = {
        outcome: r.outcome,
        category: r.category,
        rule: r.rule,
        file: r.file,
        line: r.line,
        pair: r.pair,
        framework: r.framework,
        cwe: r.cwe,
        title: r.title,
      };
      return [r.id, entry] as const;
    }),
  );

  const pluginRecord = sortedRecord(
    [...plugins.values()].map((p) => {
      const entry: BaselinePlugin = { package: p.packageName, rules: Object.keys(p.plugin.rules).sort() };
      return [p.short, entry] as const;
    }),
  );

  return { $comment: COMMENT, schema: 1, plugins: pluginRecord, rules, categories: categoryRecord, cases };
}

export function serializeBaseline(baseline: Baseline): string {
  return `${JSON.stringify(baseline, null, 2)}\n`;
}

export interface CaseChange {
  readonly id: string;
  readonly rule: string;
  readonly from: Outcome | null;
  readonly to: Outcome | null;
}

export interface Comparison {
  /** TP -> FN and TN -> FP: what the ratchet forbids. */
  readonly regressions: readonly CaseChange[];
  /** FN -> TP and FP -> TN: to lock in with `--update`. */
  readonly improvements: readonly CaseChange[];
  /** Cases the baseline does not know yet (new known gaps or new wins). */
  readonly added: readonly CaseChange[];
  readonly removed: readonly CaseChange[];
  /** Whether the committed file is byte-for-byte what `--update` would write. */
  readonly upToDate: boolean;
}

export function compareBaseline(committed: Baseline | null, current: Baseline): Comparison {
  const before = committed?.cases ?? {};
  const regressions: CaseChange[] = [];
  const improvements: CaseChange[] = [];
  const added: CaseChange[] = [];
  const removed: CaseChange[] = [];
  for (const [id, now] of Object.entries(current.cases)) {
    const was = before[id];
    if (was === undefined) {
      added.push({ id, rule: now.rule, from: null, to: now.outcome });
    } else if (was.outcome !== now.outcome) {
      const change = { id, rule: now.rule, from: was.outcome, to: now.outcome };
      const worse = (was.outcome === 'TP' && now.outcome === 'FN') || (was.outcome === 'TN' && now.outcome === 'FP');
      (worse ? regressions : improvements).push(change);
    }
  }
  for (const [id, was] of Object.entries(before)) {
    if (!(id in current.cases)) removed.push({ id, rule: was.rule, from: was.outcome, to: null });
  }
  const upToDate = committed !== null && serializeBaseline(committed) === serializeBaseline(current);
  return { regressions, improvements, added, removed, upToDate };
}
