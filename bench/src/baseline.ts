/**
 * The committed baseline (`bench/baseline.json`) and the ratchet that guards it.
 *
 * The baseline records the outcome of every case, plus the per-rule and
 * per-category scores derived from them (the docs site renders those). The
 * ratchet compares case by case rather than rate by rate, so adding a case a
 * rule misses lowers no one's guard: it is a new known gap, recorded by
 * `bun run bench --update`. What fails is a case that got worse:
 *
 *   TP -> FN   the rule stopped catching something it caught (detection drops)
 *   TN -> FP   the rule started firing on a safe twin (false alarms rise)
 *
 * `--check` also fails when the baseline is merely out of date (an improvement,
 * a new or removed case, a changed title), so the numbers on the site are
 * always the numbers of the tree. `--update` refuses to record a regression
 * unless `--allow-regressions` is passed, and refuses to drop a TP or TN case
 * (deleting a case is the other way to hide a regression) unless
 * `--allow-removals` is passed, so either is a visible choice in the diff of
 * baseline.json, never a side effect.
 *
 * Variants (semantics-preserving rewrites of each case, see `variants/`) are
 * recorded and ratcheted the same way, outcome by outcome under ids of the
 * form `<file>~<transform>#<rule>`, plus a per-rule, per-transform count of
 * the variants whose verdict differs from their case's.
 */
import type { Category } from './corpus';
import { scoreBy, scoreOf, type Score } from './metrics';
import type { CaseResult, LoadedPlugin, Outcome, Report } from './score';
import type { VariantResult } from './variants/score';

export interface BaselineCase {
  readonly outcome: Outcome;
  readonly category: string;
  readonly rule: string;
  readonly file: string;
  readonly line: number | null;
  readonly pair: string;
  readonly framework: string;
  readonly cwe: string | null;
  readonly title: string;
}

export interface BaselineRule extends Score {
  /** Reports on an unlabelled line of a vulnerable case: not counted in the four, often a real false alarm. */
  readonly extra: number;
  /** Safe cases of other categories this rule reported (FP cases, outside the paired rates). */
  readonly crossFp: number;
  /** Safe cases of other categories this rule ran on. */
  readonly crossSafe: number;
  /** `recommended` when the preset turns it on, `override` when a category enables it. */
  readonly enabledBy: 'recommended' | 'override';
  readonly categories: readonly string[];
  readonly description: string;
  readonly url: string | null;
}

export interface BaselineCategory extends Score {
  readonly extra: number;
  readonly title: string;
  readonly cwe: string | null;
  readonly rules: readonly string[];
  readonly pairs: number;
  /** The rule entries layered over `recommended` for this category, as written in category.json. */
  readonly overrides: Readonly<Record<string, unknown>>;
}

export interface BaselinePlugin {
  readonly package: string;
  /** Every rule the plugin exports, measured or not, so the site can say which have no cases yet. */
  readonly rules: readonly string[];
}

/** How the variants of one rule under one transform compare with their cases. */
export interface VariantTransformScore {
  readonly variants: number;
  /** Same outcome as the case. */
  readonly holds: number;
  /** The case is caught (TP), the variant is missed (FN). */
  readonly missed: number;
  /** The case is left alone (TN), the variant is reported (FP). */
  readonly falseAlarms: number;
  /** The case is a known gap (FN or FP) and the variant is not: the verdict still depends on the shape. */
  readonly gained: number;
}

export interface BaselineVariantRule extends Score {
  readonly transforms: Readonly<Record<string, VariantTransformScore>>;
}

export interface Baseline {
  readonly $comment: string;
  readonly schema: 2;
  readonly plugins: Readonly<Record<string, BaselinePlugin>>;
  readonly rules: Readonly<Record<string, BaselineRule>>;
  readonly categories: Readonly<Record<string, BaselineCategory>>;
  readonly cases: Readonly<Record<string, BaselineCase>>;
  /** Scores over the variants, per rule, with the per-transform comparison against the cases. */
  readonly variantRules: Readonly<Record<string, BaselineVariantRule>>;
  /** The outcome of every variant, keyed `<file>~<transform>#<rule>`. */
  readonly variants: Readonly<Record<string, Outcome>>;
}

const COMMENT =
  'Generated by `bun run bench --update` from bench/corpus. Do not edit by hand: CI fails when this file and the tree disagree.';

function sortedRecord<T>(entries: Iterable<readonly [string, T]>): Record<string, T> {
  return Object.fromEntries([...entries].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

/** How a variant's outcome relates to its case's. */
export function variantFlip(base: Outcome, variant: Outcome): keyof Omit<VariantTransformScore, 'variants'> {
  if (base === variant) return 'holds';
  if (base === 'TP') return 'missed';
  if (base === 'TN') return 'falseAlarms';
  return 'gained';
}

function buildVariantRules(results: readonly CaseResult[], variantResults: readonly VariantResult[]): Record<string, BaselineVariantRule> {
  const baseOutcome = new Map(results.map((r) => [r.id, r.outcome]));
  const scores = scoreBy(variantResults, (r) => r.rule);
  return sortedRecord(
    [...scores].map(([rule, score]) => {
      const transforms = new Map<string, { variants: number; holds: number; missed: number; falseAlarms: number; gained: number }>();
      for (const r of variantResults.filter((v) => v.rule === rule)) {
        const base = baseOutcome.get(r.baseId);
        if (base === undefined) continue;
        const entry = transforms.get(r.transform) ?? { variants: 0, holds: 0, missed: 0, falseAlarms: 0, gained: 0 };
        entry.variants++;
        entry[variantFlip(base, r.outcome)]++;
        transforms.set(r.transform, entry);
      }
      return [rule, { ...score, transforms: sortedRecord(transforms) }] as const;
    }),
  );
}

export function buildBaseline(
  results: readonly CaseResult[],
  reports: readonly Report[],
  categories: readonly Category[],
  plugins: ReadonlyMap<string, LoadedPlugin>,
  variantResults: readonly VariantResult[] = [],
): Baseline {
  // The rates come from a rule's own categories, where every vulnerable case
  // has a twin: that is the paired measurement. A rule that also runs on other
  // categories' safe code (a preset rule runs everywhere) gets those negatives
  // as cases (so the ratchet guards them) and as the `crossFp` / `crossSafe`
  // counts, but not in its rates, where hundreds of unrelated TNs would only
  // dilute the false-alarm rate.
  const ownRules = new Map(categories.map((c) => [c.id, new Set(c.config.rules)]));
  const isOwn = (r: CaseResult): boolean => ownRules.get(r.category)?.has(r.rule) === true;
  const own = results.filter(isOwn);
  const cross = results.filter((r) => !isOwn(r));
  const ruleScores = scoreBy(own, (r) => r.rule);
  const categoryScores = scoreBy(own, (r) => r.category);
  const extras = reports.filter((r) => r.role === 'extra');
  const extraFor = (rule: string): number =>
    extras.filter((r) => r.ruleId === `noctcore-${rule}`).length;
  const extraIn = (category: Category): number =>
    extras.filter(
      (r) => r.file.startsWith(`${category.id}/`) && category.config.rules.some((rule) => r.ruleId === `noctcore-${rule}`),
    ).length;

  const rules = sortedRecord(
    [...ruleScores].map(([rule, score]) => {
      const [short = '', name = ''] = rule.split('/');
      const plugin = plugins.get(short);
      const meta = plugin?.plugin.rules[name]?.meta?.docs;
      const owning = categories.filter((c) => c.config.rules.includes(rule)).map((c) => c.id);
      const entry: BaselineRule = {
        ...score,
        extra: extraFor(rule),
        crossFp: cross.filter((r) => r.rule === rule && r.outcome === 'FP').length,
        crossSafe: cross.filter((r) => r.rule === rule).length,
        enabledBy: plugin?.recommended.has(name) === true ? 'recommended' : 'override',
        categories: owning,
        description: meta?.description ?? '',
        url: meta?.url ?? null,
      };
      return [rule, entry] as const;
    }),
  );

  const categoryRecord = sortedRecord(
    categories.map((category) => {
      const entry: BaselineCategory = {
        ...(categoryScores.get(category.id) ?? scoreOf([])),
        extra: extraIn(category),
        title: category.config.title,
        cwe: category.config.cwe,
        rules: category.config.rules,
        pairs: new Set(category.cases.map((c) => c.meta.pair)).size,
        overrides: category.config.overrides,
      };
      return [category.id, entry] as const;
    }),
  );

  const cases = sortedRecord(
    results.map((r) => {
      const entry: BaselineCase = {
        outcome: r.outcome,
        category: r.category,
        rule: r.rule,
        file: r.file,
        line: r.line,
        pair: r.pair,
        framework: r.framework,
        cwe: r.cwe,
        title: r.title,
      };
      return [r.id, entry] as const;
    }),
  );

  const pluginRecord = sortedRecord(
    [...plugins.values()].map((p) => {
      const entry: BaselinePlugin = { package: p.packageName, rules: Object.keys(p.plugin.rules).sort() };
      return [p.short, entry] as const;
    }),
  );

  return {
    $comment: COMMENT,
    schema: 2,
    plugins: pluginRecord,
    rules,
    categories: categoryRecord,
    cases,
    variantRules: buildVariantRules(results, variantResults),
    variants: sortedRecord(variantResults.map((r) => [r.id, r.outcome] as const)),
  };
}

export function serializeBaseline(baseline: Baseline): string {
  return `${JSON.stringify(baseline, null, 2)}\n`;
}

export interface CaseChange {
  readonly id: string;
  readonly rule: string;
  readonly from: Outcome | null;
  readonly to: Outcome | null;
}

export interface Comparison {
  /** TP -> FN and TN -> FP: what the ratchet forbids. */
  readonly regressions: readonly CaseChange[];
  /** FN -> TP and FP -> TN: to lock in with `--update`. */
  readonly improvements: readonly CaseChange[];
  /** Cases the baseline does not know yet (new known gaps or new wins). */
  readonly added: readonly CaseChange[];
  readonly removed: readonly CaseChange[];
  /** Removed cases that were TP or TN: protection that would disappear with them. */
  readonly removedProtection: readonly CaseChange[];
  /** Whether the committed file is byte-for-byte what `--update` would write. */
  readonly upToDate: boolean;
}

/** `<file>#<rule>` or `<file>#<rule>#<n>`: the rule part. File paths never contain `#`. */
function ruleOfId(id: string): string {
  return id.slice(id.indexOf('#') + 1).replace(/#\d+$/u, '');
}

/** Every recorded outcome, corpus cases and variants alike, by id. */
function outcomes(baseline: Baseline | null): Map<string, { outcome: Outcome; rule: string }> {
  const index = new Map<string, { outcome: Outcome; rule: string }>();
  for (const [id, c] of Object.entries(baseline?.cases ?? {})) index.set(id, { outcome: c.outcome, rule: c.rule });
  // A baseline written before variants existed has no `variants`.
  for (const [id, outcome] of Object.entries(baseline?.variants ?? {})) index.set(id, { outcome, rule: ruleOfId(id) });
  return index;
}

export function compareBaseline(committed: Baseline | null, current: Baseline): Comparison {
  const before = outcomes(committed);
  const now = outcomes(current);
  const regressions: CaseChange[] = [];
  const improvements: CaseChange[] = [];
  const added: CaseChange[] = [];
  const removed: CaseChange[] = [];
  for (const [id, entry] of now) {
    const was = before.get(id);
    if (was === undefined) {
      added.push({ id, rule: entry.rule, from: null, to: entry.outcome });
    } else if (was.outcome !== entry.outcome) {
      const change = { id, rule: entry.rule, from: was.outcome, to: entry.outcome };
      const worse = (was.outcome === 'TP' && entry.outcome === 'FN') || (was.outcome === 'TN' && entry.outcome === 'FP');
      (worse ? regressions : improvements).push(change);
    }
  }
  for (const [id, was] of before) {
    if (!now.has(id)) removed.push({ id, rule: was.rule, from: was.outcome, to: null });
  }
  const upToDate = committed !== null && serializeBaseline(committed) === serializeBaseline(current);
  const removedProtection = removed.filter((c) => c.from === 'TP' || c.from === 'TN');
  return { regressions, improvements, added, removed, removedProtection, upToDate };
}
